def card_title(stem):
    return TITLE[stem.replace("_Swimsuit", "")]
def card_type(stem):
    base = stem.replace("_Swimsuit", "")
    if base in SPECIAL_TYPE: return SPECIAL_TYPE[base]
    if "S-Craft" in base or "S-craft" in base: return "S-Craft"
    if base in SKILL: return "Skill"
    return "Craft"
